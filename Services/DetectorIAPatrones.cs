using System.Text.RegularExpressions;
using web_analizador_de_plagios.Data.Models;

namespace web_analizador_de_plagios.Services;

/// <summary>
/// Detector heurístico y explicable de señales compatibles con código generado por IA.
/// No emite una conclusión disciplinaria: agrega indicadores auditables para que el
/// docente realice la entrevista de defensa.
/// </summary>
public sealed class DetectorIAPatrones
{
    private static readonly Regex IdentificadoresRegex = new(@"[A-Za-z_][A-Za-z0-9_]*", RegexOptions.Compiled | RegexOptions.CultureInvariant);
    private static readonly Regex ComentarioLineaRegex = new(@"^\s*//[/!]?\s*(?<texto>.+)$", RegexOptions.Compiled | RegexOptions.CultureInvariant);
    private static readonly Regex BloqueComentarioRegex = new(@"/\*.*?\*/", RegexOptions.Compiled | RegexOptions.Singleline | RegexOptions.CultureInvariant);
    private static readonly Regex FraseAsistenteRegex = new(
        @"\b(as an ai|como modelo de lenguaje|aqu[ií] tienes|here is the|here's the|espero que (esto|te)|hope this helps|let me know|si necesitas (algo|ayuda)|no dudes en)\b",
        RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex MarcaIARegex = new(
        @"\b(chatgpt|openai|copilot|claude|gemini|generado por (una )?ia|generated by ai|inteligencia artificial)\b",
        RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex ComentarioRedundanteRegex = new(
        @"^\s*//[/!]?\s*(inicializa|inicializar|crea|crear|declara|declarar|recorre|recorrer|imprime|imprimir|calcula|calcular|obtiene|obtener|asigna|asignar|define|definir|llama|llamar|retorna|devuelve|inicializa la|crea la|create|initialize|declare|loop through|print|calculate|assign|return the|define the)\b",
        RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex PlaceholderRegex = new(
        @"\b(todo|your code here|tu c[oó]digo aqu[ií]|implementar|pending|placeholder|lorem ipsum|example\.com|completar esta parte)\b",
        RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex MarcadorPersonalRegex = new(
        @"\b(yo|mi |mis |profesor|profe|carnet|secci[oó]n|me cost[oó]|entend[ií]|compa[nñ]ero|ayuda de|seg[uú]n lo visto|en clase)\b",
        RegexOptions.Compiled | RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
    private static readonly Regex ConsoleRegex = new(@"Console\.(WriteLine|Write)\s*\(", RegexOptions.Compiled | RegexOptions.CultureInvariant);
    private static readonly Regex CatchGenericoRegex = new(@"catch\s*\(\s*Exception(\s+\w+)?\s*\)", RegexOptions.Compiled | RegexOptions.CultureInvariant);
    private static readonly Regex VarRegex = new(@"\bvar\s+[A-Za-z_][A-Za-z0-9_]*\s*(=|;)", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    private static readonly HashSet<string> NombresGenericos = new(StringComparer.OrdinalIgnoreCase)
    {
        "result", "resultado", "results", "resultados", "data", "datos", "temp", "temporal", "value", "valor",
        "item", "elemento", "list", "lista", "array", "arreglo", "aux", "auxiliar", "foo", "bar", "example",
        "ejemplo", "prueba", "test", "test1", "output", "salida", "input", "entrada", "obj", "objeto", "info",
        "variable", "var1", "x1", "myclass", "myvariable", "numero", "texto", "string1", "first", "second",
        "response", "request", "respuesta", "solicitud", "count", "contador", "index", "indice", "info1"
    };

    private readonly NormalizadorCodigo _normalizador;
    private readonly AnalizadorEstructura _estructura;

    public DetectorIAPatrones(NormalizadorCodigo normalizador, AnalizadorEstructura estructura)
    {
        _normalizador = normalizador;
        _estructura = estructura;
    }

    public ResultadoDeteccionIA Detectar(string codigo, EstructuraCodigo? estructura = null)
    {
        codigo ??= string.Empty;
        var normalizacion = _normalizador.Normalizar(codigo);
        estructura ??= _estructura.Analizar(codigo, normalizacion);

        var lineas = AnalizadorSimilitud.NormalizarLineas(codigo);
        var noVacias = lineas.Where(l => !string.IsNullOrWhiteSpace(l)).Select(l => l.Trim()).ToList();
        var comentarios = new List<string>();
        foreach (var linea in lineas)
        {
            var match = ComentarioLineaRegex.Match(linea);
            if (match.Success)
            {
                comentarios.Add(match.Groups["texto"].Value.Trim());
            }
        }

        foreach (Match bloque in BloqueComentarioRegex.Matches(codigo))
        {
            comentarios.Add(bloque.Value.Replace("/*", string.Empty).Replace("*/", string.Empty).Trim());
        }

        var textoComentarios = string.Join(" ", comentarios);
        var lineasDoc = lineas.Count(l => l.TrimStart().StartsWith("///", StringComparison.Ordinal));
        var densidadComentarios = normalizacion.LineasTotales == 0
            ? 0
            : (double)normalizacion.LineasComentario / normalizacion.LineasTotales;

        var longitudes = noVacias.Select(l => (double)l.Length).ToList();
        var promedioLongitud = longitudes.Count == 0 ? 0 : longitudes.Average();
        var desviacion = longitudes.Count <= 1
            ? 0
            : Math.Sqrt(longitudes.Sum(l => Math.Pow(l - promedioLongitud, 2)) / longitudes.Count);

        var lineasRepetidas = noVacias.Count == 0
            ? 0
            : 1d - (double)noVacias.Distinct(StringComparer.Ordinal).Count() / noVacias.Count;

        var tokensIdentificadores = _normalizador.Normalizar(codigo, normalizarIdentificadores: false).Tokens
            .Where(t => t.Length > 0 && (char.IsLetter(t[0]) || t[0] == '_') && !NormalizadorCodigo.EsPalabraClave(t))
            .Distinct(StringComparer.Ordinal)
            .ToList();
        var genericos = tokensIdentificadores.Where(NombresGenericos.Contains).ToList();
        var ratioGenericos = tokensIdentificadores.Count == 0 ? 0 : (double)genericos.Count / tokensIdentificadores.Count;

        var lineasComentarioRedundante = lineas.Count(l => ComentarioRedundanteRegex.IsMatch(l));
        var consoleWrites = ConsoleRegex.Matches(codigo).Count;
        var catchGenericos = CatchGenericoRegex.Matches(codigo).Count;
        var declaracionesVar = VarRegex.Matches(codigo).Count;
        var ratioVar = estructura.Variables.Count == 0 ? 0 : (double)declaracionesVar / estructura.Variables.Count;
        var metodosExpresion = estructura.Metodos.Count(m => m.EsExpresion);
        var ratioExpresion = estructura.Metodos.Count == 0 ? 0 : (double)metodosExpresion / estructura.Metodos.Count;
        var metodosSimples = estructura.Metodos.Count(m => m.LineaFin - m.LineaInicio + 1 <= 9);
        var promedioLineasMetodo = estructura.Metodos.Count == 0
            ? 0
            : estructura.Metodos.Average(m => m.LineaFin - m.LineaInicio + 1);
        var complejidadMaxima = estructura.Metodos.Count == 0 ? 0 : estructura.Metodos.Max(m => m.Complejidad);
        var placeholders = PlaceholderRegex.Matches(textoComentarios).Count;
        var marcasPersonales = MarcadorPersonalRegex.Matches(textoComentarios).Count;

        var indicadores = new List<IndicadorIA>();
        var puntaje = 4d;

        void Sumar(string nombre, string descripcion, string evidencia, double aporte, string severidad)
        {
            if (aporte <= 0)
            {
                return;
            }

            puntaje += aporte;
            indicadores.Add(new IndicadorIA
            {
                Nombre = nombre,
                Descripcion = descripcion,
                Evidencia = evidencia,
                Aporte = Math.Round(aporte, 1),
                Severidad = severidad
            });
        }

        void Mitigar(string nombre, string descripcion, string evidencia, double aporte)
        {
            puntaje -= aporte;
            indicadores.Add(new IndicadorIA
            {
                Nombre = nombre,
                Descripcion = descripcion,
                Evidencia = evidencia,
                Aporte = -Math.Round(aporte, 1),
                Severidad = "Mitigante"
            });
        }

        var marcasIa = MarcaIARegex.Matches(textoComentarios);
        if (marcasIa.Count > 0)
        {
            Sumar("Referencia explícita a IA",
                "Los comentarios mencionan herramientas de IA o generación automática.",
                $"«{marcasIa[0].Value}»",
                35, "Alta");
        }
        else if (FraseAsistenteRegex.IsMatch(textoComentarios))
        {
            var coincidencia = FraseAsistenteRegex.Match(textoComentarios);
            Sumar("Frase de asistente conversacional",
                "El texto incluye fórmulas típicas de un asistente que entrega código.",
                $"«{coincidencia.Value}»",
                20, "Alta");
        }

        if (densidadComentarios >= 0.42)
        {
            Sumar("Densidad de comentarios muy alta",
                $"El {densidadComentarios:P0} de las líneas son comentarios, un patrón frecuente en código explicado automáticamente.",
                $"{normalizacion.LineasComentario} líneas de comentario de {normalizacion.LineasTotales}.",
                12, "Media");
        }
        else if (densidadComentarios >= 0.28)
        {
            Sumar("Densidad de comentarios elevada",
                $"El {densidadComentarios:P0} de las líneas son comentarios.",
                $"{normalizacion.LineasComentario} líneas de comentario.",
                8, "Baja");
        }
        else if (densidadComentarios >= 0.18)
        {
            Sumar("Comentarios por encima de lo habitual",
                "La proporción de comentarios es superior a la de un archivo típico de estudiante.",
                $"{densidadComentarios:P0} del archivo.",
                4, "Baja");
        }

        if (lineasComentarioRedundante >= 3)
        {
            var ejemplos = lineas.Select(l => l.Trim())
                .Where(l => ComentarioRedundanteRegex.IsMatch(l))
                .Take(2)
                .ToList();
            Sumar("Comentarios que narran lo obvio",
                "Hay varias líneas que describen literalmente la instrucción siguiente, un estilo común en respuestas generadas.",
                string.Join(" · ", ejemplos),
                lineasComentarioRedundante >= 6 ? 10 : 7,
                "Media");
        }

        if (lineasDoc >= 2 && estructura.Metodos.Count > 0 && promedioLineasMetodo <= 18)
        {
            Sumar("Documentación XML desproporcionada",
                "Se documentan con XML métodos muy breves, algo frecuente en código generado con plantillas.",
                $"{lineasDoc} líneas de documentación para métodos de {promedioLineasMetodo:F0} líneas en promedio.",
                8, "Media");
        }
        else if (lineasDoc >= 3)
        {
            Sumar("Documentación XML extensa",
                "El archivo contiene documentación XML abundante.",
                $"{lineasDoc} líneas ///.",
                4, "Baja");
        }

        if (ratioGenericos >= 0.30)
        {
            Sumar("Identificadores genéricos",
                "Una parte importante de los nombres son comodines poco ligados al problema (result, data, temp...).",
                string.Join(", ", genericos.Take(6)),
                8, "Media");
        }
        else if (ratioGenericos >= 0.16)
        {
            Sumar("Uso moderado de nombres genéricos",
                "Se observan varios identificadores genéricos.",
                string.Join(", ", genericos.Take(6)),
                5, "Baja");
        }

        if (desviacion < 9 && promedioLongitud > 28 && noVacias.Count > 25)
        {
            Sumar("Longitud de línea uniforme",
                "Las líneas tienen longitudes muy homogéneas; el código escrito manualmente suele ser más irregular.",
                $"Desviación de {desviacion:F1} caracteres sobre {noVacias.Count} líneas.",
                8, "Baja");
        }
        else if (desviacion < 14 && noVacias.Count > 25)
        {
            Sumar("Formato muy regular",
                "La estructura visual del archivo es especialmente uniforme.",
                $"Desviación de {desviacion:F1} caracteres.",
                4, "Baja");
        }

        if (lineasRepetidas >= 0.25 && noVacias.Count > 30)
        {
            Sumar("Patrones repetidos",
                "Se repiten muchas líneas con el mismo esqueleto, lo que sugiere plantillas o generación en serie.",
                $"{lineasRepetidas:P0} de líneas no vacías son duplicadas.",
                8, "Media");
        }
        else if (lineasRepetidas >= 0.15 && noVacias.Count > 30)
        {
            Sumar("Repetición moderada de patrones",
                "Hay bloques de líneas repetidas.",
                $"{lineasRepetidas:P0} de líneas duplicadas.",
                4, "Baja");
        }

        if (consoleWrites >= 2 && estructura.Metodos.Count <= 5)
        {
            Sumar("Estilo de ejemplo con consola",
                "El programa imprime resultados de forma demostrativa y tiene pocos métodos, un patrón típico de ejemplos generados.",
                $"{consoleWrites} llamadas a Console.",
                5, "Baja");
        }

        if (ratioVar >= 0.75 && estructura.Variables.Count >= 8)
        {
            Sumar("Uso sistemático de var",
                "Casi todas las declaraciones usan var, otra marca de estilo homogéneo.",
                $"{declaracionesVar} de {estructura.Variables.Count} declaraciones.",
                4, "Baja");
        }

        if (ratioExpresion >= 0.6 && estructura.Metodos.Count >= 3)
        {
            Sumar("Métodos de expresión uniformes",
                "Predominan métodos con cuerpo de expresión, un estilo compacto y uniforme.",
                $"{metodosExpresion} de {estructura.Metodos.Count} métodos.",
                4, "Baja");
        }

        if (catchGenericos > 0)
        {
            Sumar("Captura genérica de excepciones",
                "Se captura Exception sin tratamiento específico visible, patrón frecuente en plantillas.",
                $"{catchGenericos} bloque(s) catch (Exception).",
                4, "Baja");
        }

        if (placeholders > 0)
        {
            Sumar("Marcadores de plantilla",
                "Quedaron marcadores típicos de esqueleto o ejemplo en los comentarios.",
                $"{placeholders} marcador(es) tipo TODO/placeholder/example.",
                placeholders >= 2 ? 8 : 6,
                "Media");
        }

        // Señales que reducen la probabilidad: contexto humano verificable.
        if (marcasPersonales >= 2)
        {
            Mitigar("Comentarios con contexto personal",
                "Hay referencias a clase, profesor o experiencia propia que sugieren autoría humana.",
                $"{marcasPersonales} referencias personales.",
                6);
        }

        var lineasConTabulador = lineas.Count(l => l.StartsWith('\t'));
        var lineasConEspacios = lineas.Count(l => l.StartsWith("  ", StringComparison.Ordinal));
        if (lineasConTabulador > 2 && lineasConEspacios > 2)
        {
            Mitigar("Formato irregular",
                "Se mezclan tabuladores y espacios, una inconsistencia poco común en código generado.",
                $"{lineasConTabulador} líneas con tabulador y {lineasConEspacios} con espacios.",
                5);
        }

        if (complejidadMaxima >= 16 || promedioLineasMetodo >= 55)
        {
            Mitigar("Complejidad o extensión atípica",
                "Los métodos son largos o complejos, lo que reduce el patrón de respuestas breves y uniformes.",
                $"Complejidad máxima {complejidadMaxima}; promedio de {promedioLineasMetodo:F0} líneas por método.",
                6);
        }

        var identificadoresEspecificos = tokensIdentificadores
            .Where(t => t.Length >= 9 && !NombresGenericos.Contains(t))
            .Take(4)
            .ToList();
        if (identificadoresEspecificos.Count >= 3)
        {
            Mitigar("Vocabulario específico del dominio",
                "Hay identificadores largos y propios del problema, señal de diseño contextual.",
                string.Join(", ", identificadoresEspecificos),
                3);
        }

        if (normalizacion.LineasCodigo < 8)
        {
            puntaje = Math.Min(puntaje, 30);
            Mitigar("Muestra muy pequeña",
                "El archivo tiene pocas líneas; la estimación es poco fiable y no debe usarse como evidencia única.",
                $"{normalizacion.LineasCodigo} líneas de código.",
                8);
        }

        puntaje = Math.Clamp(puntaje, 0, 100);
        var nivel = puntaje switch
        {
            >= 80 => "Muy alto",
            >= 60 => "Alto",
            >= 40 => "Medio",
            >= 20 => "Bajo",
            _ => "Muy bajo"
        };

        var principales = indicadores
            .Where(i => i.Aporte > 0)
            .OrderByDescending(i => i.Aporte)
            .Take(2)
            .Select(i => i.Nombre.ToLowerInvariant())
            .ToList();

        var resumen = principales.Count == 0
            ? "No se encontraron señales fuertes de generación automática. Esto no certifica autoría: complemente con la defensa oral."
            : $"Se detectaron señales compatibles con generación asistida, principalmente {string.Join(" y ", principales)}. La estimación es heurística y no sustituye la entrevista.";

        return new ResultadoDeteccionIA
        {
            Probabilidad = Math.Round(puntaje, 1),
            Nivel = nivel,
            Resumen = resumen,
            Indicadores = indicadores.OrderByDescending(i => i.Aporte).ToList(),
            Metricas = new MetricasEstilo
            {
                LineasTotales = normalizacion.LineasTotales,
                LineasComentario = normalizacion.LineasComentario,
                DensidadComentarios = Math.Round(densidadComentarios * 100, 1),
                PromedioLongitudLinea = Math.Round(promedioLongitud, 1),
                DesviacionLongitudLinea = Math.Round(desviacion, 1),
                IdentificadoresGenericos = genericos.Count,
                DeclaracionesDoc = lineasDoc,
                RatioLineasRepetidas = Math.Round(lineasRepetidas * 100, 1),
                MetodosSimples = metodosSimples,
                RatioVar = Math.Round(ratioVar * 100, 1),
                MetodosExpresion = metodosExpresion,
                ConsoleWrites = consoleWrites,
                CatchGenericos = catchGenericos
            }
        };
    }
}
